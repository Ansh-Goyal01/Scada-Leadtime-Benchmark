"""Phase 6 item 2: quote each protected item (plan section 2) with its location in the new PDF.
Reads revision-artifacts/inventory_after.csv (sentences, captions, table cells);
writes revision-artifacts/phase6/protected_quotes.md. A missing item prints MISSING.
"""
import csv, pathlib, re

RA = pathlib.Path(__file__).resolve().parents[2] / "revision-artifacts"
rows = list(csv.DictReader(open(RA / "inventory_after.csv", encoding="utf-8")))
sent = [r for r in rows if r["item_type"] == "sentence"]
cells = [r for r in rows if r["item_type"] == "table-cell"]
cites = {r["group_id"]: r["section"] for r in rows if r["item_type"] == "citation"}

ITEMS = [
    ("D6/F4", "coarsening level per dataset; not a test of raw-signal averaging", [r"On IMS the sweep coarsens", r"not a test of raw-signal averaging"]),
    ("D17", "+-1 h margin and its justification at first use", [r"resolution at which a (maintenance )?planner can act"]),
    ("D18/D16", "bounded margin; five below-zero cells; widest -0.45 h", [r"five cells have an interval", r"-0\.45"]),
    ("D19", "App. C both labels side by side, per-run differences, effective n", [r"report both arms side by side", r"effective sample size is detector-dependent"]),
    ("D20", "lifetime asymmetry in Sec. 8, abstract, conclusion", [r"scale of minutes"]),
    ("D3", "deep models as rows in the trade-off table; per-threshold statement", [r"checked per threshold"]),
    ("D4", "one-class SVM in results tables; N = 44", [r"N ?= ?44"]),
    ("F2", "gated contrast in the body with its power cost", [r"roughly a halving"]),
    ("F3/G4", "deep-model scoping in abstract and conclusion; 20-335 windows; 2.0-5.5 x 10^4 parameters", [r"do not overtake", r"20 and 335", r"2\.0-5\.5"]),
    ("G1", "onset-estimator bias k sigma_b/m, sigma_b/m after Algorithm 1", [r"late by approximately"]),
    ("G2", "Sec. 7.3 signal-theoretic argument; 'we claim no conservation result'", [r"followed by downsampling", r"no conservation result"]),
    ("G3", "raw lead invariant, 0.000 h across 99 cells", [r"0\.000 h across all 99"]),
    ("G7", "Data Availability enumeration of ONGC artifacts by path", [r"ongc_ ?health_ ?indicator"]),
    ("G8", "RUL-benchmarking limitation in Sec. 8", [r"Limited external benchmarking"]),
    ("Corrections", "multi-seed gap result; Hotelling T2 collapsing in 2 of 5 draws at 20%", [r"collapses in 2 of the 5 draws"]),
]
L = ["# Protected items -- quoted from the new PDF (generated by protected_quotes.py)", ""]
for tag, what, pats in ITEMS:
    L.append("## %s -- %s" % (tag, what))
    for p in pats:
        hits = [r for r in sent if re.search(p, r["context"].replace("−", "-").replace("–", "-"), re.I)]
        if not hits:
            L.append("- `%s`: **MISSING**" % p)
            continue
        locs = sorted({h["location"] for h in hits})
        L.append("- `%s` found in: %s" % (p, "; ".join(locs)))
        L.append("  > %s" % hits[0]["context"][:400])
    L.append("")
L.append("## G5 -- deep-model architecture table in the paper")
L.append("- tab:deeparch cells in the new PDF: %d" % sum(1 for c in cells if c["group_id"] == "tab:deeparch"))
L.append("")
L.append("## D1/F1/G6 -- the six related-work citations")
for k in ("lavin2015nab", "tatbul2018", "wu2023flawed", "lorden1971", "moustakides1986", "pollak1985"):
    L.append("- %s: %s" % (k, cites.get(k, "**MISSING**")))
(RA / "phase6/protected_quotes.md").write_text("\n".join(L) + "\n", encoding="utf-8")
print("MISSING" in "\n".join(L), sum(1 for x in L if "MISSING" in x))
